import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import os

st.set_page_config(
    page_title="Executive Turnover Dashboard",
    page_icon="T",
    layout="wide",
)

# Custom CSS
st.markdown("""
<style>
    .block-container { padding-top: 1.5rem; }
    div[data-testid="stMetric"] {
        background-color: #ffffff;
        border-radius: 10px;
        box-shadow: 0 2px 8px rgba(0,0,0,0.08);
        padding: 18px 20px;
    }
    div[data-testid="stMetric"] label { font-size: 0.85rem; }
</style>
""", unsafe_allow_html=True)

st.title("Macro-Level Employee Turnover Dashboard")
st.markdown("Monitor company-wide turnover risk and evaluate retention strategies at a glance.")

# ---------------------------------------------------------------------------
# Data Loading
# ---------------------------------------------------------------------------
DATA_PATH = "predictions_output.xlsx"

@st.cache_data
def load_dashboard_data(filepath: str = DATA_PATH) -> pd.DataFrame:
    """Load the pre-computed predictions spreadsheet (generated by main.py)."""
    if not os.path.exists(filepath):
        st.error(f"Data file **{filepath}** not found. Please run `python main.py` first.")
        return pd.DataFrame()
    df = pd.read_excel(filepath)
    return df

dashboard_df = load_dashboard_data()

if dashboard_df.empty:
    st.stop()

# ---------------------------------------------------------------------------
# KPI Section
# ---------------------------------------------------------------------------
st.markdown("### Top Indicators")
col1, col2, col3 = st.columns(3)

total_employees = len(dashboard_df)
avg_turnover_prob = dashboard_df["Turnover Probability"].mean()
high_risk_count = int(
    dashboard_df[
        dashboard_df["Risk Category"].isin(["High Risk", "Very High Risk"])
    ].shape[0]
)

with col1:
    st.metric("Total Active Employees", f"{total_employees:,}")
with col2:
    st.metric("Company-Wide Turnover Risk", f"{avg_turnover_prob * 100:.1f}%")
with col3:
    st.metric("High-Risk Headcount", f"{high_risk_count:,}")

st.markdown("---")

# ---------------------------------------------------------------------------
# Visualisations
# ---------------------------------------------------------------------------
st.markdown("### Risk Analysis Insights")

# --- Row 1: Donut + Bar side-by-side ---
left_col, right_col = st.columns(2)

# Donut Chart — Risk Distribution
with left_col:
    st.markdown("#### Risk Distribution")

    risk_order = ["Low Risk", "Medium Risk", "High Risk", "Very High Risk"]
    color_map = {
        "Low Risk": "#2ecc71",
        "Medium Risk": "#f1c40f",
        "High Risk": "#e67e22",
        "Very High Risk": "#e74c3c",
    }

    risk_counts = (
        dashboard_df["Risk Category"]
        .value_counts()
        .reindex(risk_order, fill_value=0)
        .reset_index()
    )
    risk_counts.columns = ["Risk Category", "Count"]

    fig_donut = go.Figure(
        data=[
            go.Pie(
                labels=risk_counts["Risk Category"],
                values=risk_counts["Count"],
                hole=0.55,
                marker=dict(
                    colors=[color_map[r] for r in risk_counts["Risk Category"]]
                ),
                textinfo="percent+label",
                textposition="inside",
            )
        ]
    )
    fig_donut.update_layout(
        showlegend=False,
        margin=dict(t=20, b=20, l=20, r=20),
        height=400,
    )
    st.plotly_chart(fig_donut, width="stretch", key="donut_chart")

# Bar Chart — Avg Turnover Probability by Budget Section
with right_col:
    st.markdown("#### Avg Turnover Risk by Budget Section")

    dept_risk = (
        dashboard_df.groupby("Budget Section")["Turnover Probability"]
        .mean()
        .reset_index()
    )
    dept_risk["Turnover Probability (%)"] = dept_risk["Turnover Probability"] * 100
    dept_risk = dept_risk.sort_values("Turnover Probability (%)", ascending=False).head(15)

    fig_bar = go.Figure(
        data=[
            go.Bar(
                x=dept_risk["Budget Section"].astype(str),
                y=dept_risk["Turnover Probability (%)"],
                marker_color="#e74c3c",
            )
        ]
    )
    fig_bar.update_layout(
        xaxis_title="Budget Section",
        yaxis_title="Avg Turnover Risk (%)",
        margin=dict(t=20, b=20, l=40, r=20),
        height=400,
    )
    st.plotly_chart(fig_bar, width="stretch", key="bar_chart")

st.markdown("---")

# --- Row 2: Scatter Plot —  Tenure vs Turnover Probability ---
st.markdown("#### Turnover Probability vs. Tenure")

fig_scatter = go.Figure()

for cat, color in color_map.items():
    subset = dashboard_df[dashboard_df["Risk Category"] == cat]
    if subset.empty:
        continue
    fig_scatter.add_trace(
        go.Scatter(
            x=subset["Tenure (Months)"],
            y=subset["Turnover Probability"],
            mode="markers",
            name=cat,
            marker=dict(color=color, opacity=0.6, size=6),
            text=subset["Employee ID"].astype(str),
            hovertemplate="Employee: %{text}<br>Tenure: %{x} months<br>Risk: %{y:.2%}<extra></extra>",
        )
    )

fig_scatter.update_layout(
    xaxis_title="Tenure (Months)",
    yaxis_title="Turnover Probability",
    legend_title="Risk Category",
    margin=dict(t=20, b=40, l=40, r=20),
    height=450,
)
st.plotly_chart(fig_scatter, use_container_width=True, key="scatter_chart")
